def safe_replace(html, en_sub, zh_full):
    pattern = rf'>([^<]*{re.escape(en_sub)}[^<]*)<'
    m = re.search(pattern, html)
    if m:
        return html.replace(m.group(0), f'>{zh_full}<')
    return html

